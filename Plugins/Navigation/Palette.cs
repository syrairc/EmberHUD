namespace NavigationPlugin;

internal static class Palette
{
    public static readonly Color[] Presets =
    [
        Color.FromArgb(0xE6, 0x19, 0x4B), Color.FromArgb(0x00, 0xBF, 0xFF), Color.FromArgb(0xFF, 0xFF, 0xFF),
        Color.FromArgb(0xAD, 0xFF, 0x2F), Color.FromArgb(0x8A, 0x2B, 0xE2), Color.FromArgb(0x2E, 0x8B, 0x57),
        Color.FromArgb(0xFF, 0xA0, 0x7A), Color.FromArgb(0x00, 0xFF, 0x7F), Color.FromArgb(0xFF, 0x8C, 0x00),
        Color.FromArgb(0x80, 0x80, 0x00), Color.FromArgb(0x64, 0x95, 0xED), Color.FromArgb(0xDA, 0x70, 0xD6),
        Color.FromArgb(0xAA, 0xFF, 0xC3), Color.FromArgb(0x20, 0xB2, 0xAA), Color.FromArgb(0xFF, 0xE1, 0x19),
        Color.FromArgb(0x70, 0x80, 0x90), Color.FromArgb(0xCD, 0x85, 0x3F), Color.FromArgb(0xFF, 0xD8, 0xB1),
        Color.FromArgb(0xFF, 0x14, 0x93), Color.FromArgb(0x32, 0xCD, 0x32), Color.FromArgb(0xA9, 0xA9, 0xA9),
        Color.FromArgb(0xDC, 0xBE, 0xFF), Color.FromArgb(0xFF, 0x45, 0x00), Color.FromArgb(0x42, 0xD4, 0xF4),
        Color.FromArgb(0xF0, 0x32, 0xE6), Color.FromArgb(0xB2, 0x22, 0x22), Color.FromArgb(0x43, 0x63, 0xD8),
        Color.FromArgb(0x93, 0x70, 0xDB), Color.FromArgb(0xFF, 0x63, 0x47), Color.FromArgb(0xC7, 0x15, 0x85),
    ];

    public static Color Pick(IReadOnlySet<Color> used, Random random)
    {
        var free = Presets.Where(c => !used.Contains(c)).ToArray();
        var pool = free.Length > 0 ? free : Presets;
        return pool[random.Next(pool.Length)];
    }
}
